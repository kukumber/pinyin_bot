// markReplacer strips tone marks from pinyin vowels
var markReplacer = strings.NewReplacer(
	"ā", "a", "á", "a", "ǎ", "a", "à", "a",
	"Ā", "A", "Á", "A", "Ǎ", "A", "À", "A",
	"ē", "e", "é", "e", "ě", "e", "è", "e",
	"Ē", "E", "É", "E", "Ě", "E", "È", "E",
	"ī", "i", "í", "i", "ǐ", "i", "ì", "i",
	"Ī", "I", "Í", "I", "Ǐ", "I", "Ì", "I",
	"ō", "o", "ó", "o", "ǒ", "o", "ò", "o",
	"Ō", "O", "Ó", "O", "Ǒ", "O", "Ò", "O",
	"ū", "u", "ú", "u", "ǔ", "u", "ù", "u",
	"Ū", "U", "Ú", "U", "Ǔ", "U", "Ù", "U",
	"ǖ", "ü", "ǘ", "ü", "ǚ", "ü", "ǜ", "ü",
	"Ǖ", "ü", "Ǘ", "ü", "Ǚ", "ü", "Ǜ", "ü",
)

// syllables maps pinyin syllables to their Pallady Cyrillic form
var syllables = mergeSyllables()

func mergeSyllables() map[string]string {
	merged := make(map[string]string, 1024)
	for _, src := range []map[string]string{pallady6, pallady5, pallady4, pallady3, pallady2, pallady1} {
		for k, v := range src {
			merged[k] = v
		}
	}
	return merged
}

// ConvertToPallady converts pinyin text to the Cyrillic Pallady format.
// Words that are not valid pinyin syllables are left unchanged.
func ConvertToPallady(input string) string {
	var b strings.Builder
	b.Grow(len(input))

	runes := []rune(input)
	for i := 0; i < len(runes); {
		if !unicode.IsLetter(runes[i]) {
			b.WriteRune(runes[i])
			i++
			continue
		}

		j := i
		for j < len(runes) && unicode.IsLetter(runes[j]) {
			j++
		}

		word := string(runes[i:j])
		if replacement, ok := syllables[removeMarks(word)]; ok {
			b.WriteString(replacement)
		} else {
			b.WriteString(word)
		}
		i = j
	}

	return b.String()
}

// removeMarks removes the tone marks from the pinyin
func removeMarks(raw string) string {
	return markReplacer.Replace(raw)
}

